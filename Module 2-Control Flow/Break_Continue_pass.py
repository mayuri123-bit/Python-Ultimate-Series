#.............Control Flow Statements
#break----it is control flow statement that break iterating loop
for i in range(1,20):
    if i==6:
        break
    print(i)

#Continue--->control flow statement that skip present block of iteration nd continue next iteration
for j in range(1, 6):
    if j == 3:
        continue
    print(i)

#pass---> it is an type of control flow statement that does not control flow of statement it do nothing with the flow of statements
for k in range(1,4):
    if k==2:
        pass
    print(k)
#(----When user wanted to add code later in program they can create function nd pass the block of code)